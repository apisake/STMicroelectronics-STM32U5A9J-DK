#!/usr/bin/env python3
"""
Minimal TTF -> LVGL v9 bitmap font converter (lv_font_fmt_txt, 4 bpp, no compression).

Uses Pillow (FreeType) to rasterise glyphs. Thai combining marks keep their
zero advance and negative x offset, so LVGL stacks them over the previous
consonant. (LVGL does no OpenType shaping: a tone mark over an upper vowel,
e.g. "ที่", may overlap - avoid such combinations in UI strings.)

Usage:
  python3 tools/ttf2lvgl.py <ttf> <size> <c_name> <out.c> <ranges> [--tabular-digits] [--tight]
  ranges: comma separated, e.g. 0x20-0x7E,0xB0,0x0E01-0x0E3A
"""
import sys
from PIL import Image, ImageDraw, ImageFont


def parse_ranges(spec):
    cps = []
    for part in spec.split(","):
        if "-" in part:
            a, b = part.split("-")
            cps.extend(range(int(a, 0), int(b, 0) + 1))
        else:
            cps.append(int(part, 0))
    return sorted(set(cps))


def contiguous_runs(cps):
    runs, start, prev = [], cps[0], cps[0]
    for c in cps[1:]:
        if c != prev + 1:
            runs.append((start, prev))
            start = c
        prev = c
    runs.append((start, prev))
    return runs


def main():
    ttf, size, name, out, ranges = sys.argv[1], int(sys.argv[2]), sys.argv[3], sys.argv[4], sys.argv[5]
    tabular = "--tabular-digits" in sys.argv[6:]
    font = ImageFont.truetype(ttf, size)
    cps = parse_ranges(ranges)

    digit_adv = max(font.getlength(str(d)) for d in range(10)) if tabular else 0

    bitmap = bytearray()
    glyphs = []                      # (cp, bitmap_index, adv_w16, w, h, ofs_x, ofs_y)
    top_max, bot_max = 0, 0
    for cp in cps:
        ch = chr(cp)
        adv = font.getlength(ch)
        # Render on a large canvas with a known origin and take the *ink* bbox:
        # Pillow's getbbox() includes the pen origin, which is wrong for Thai marks.
        S = size * 4
        ox, oy = size * 2, size * 2                          # origin (baseline) in canvas
        canvas = Image.new("L", (S, S), 0)
        ImageDraw.Draw(canvas).text((ox, oy), ch, font=font, fill=255, anchor="ls")
        ink = canvas.getbbox()
        if ink:
            x0, y0, x1, y1 = ink[0] - ox, ink[1] - oy, ink[2] - ox, ink[3] - oy
        else:
            x0 = y0 = x1 = y1 = 0
        w, h = max(0, x1 - x0), max(0, y1 - y0)
        shift = 0
        if tabular and ch.isdigit():
            shift = int(round((digit_adv - adv) / 2))       # centre digit in fixed cell
            adv = digit_adv
        idx = len(bitmap)
        if w and h:
            img = canvas.crop(ink)
            px = img.tobytes()
            nib = [(v + 8) >> 4 if v < 248 else 15 for v in px]   # 8-bit -> 4-bit
            if len(nib) % 2:
                nib.append(0)
            for i in range(0, len(nib), 2):
                bitmap.append((nib[i] << 4) | nib[i + 1])
            top_max = max(top_max, -y0)
            bot_max = max(bot_max, y1)
        glyphs.append((cp, idx, int(round(adv * 16)), w, h, x0 + shift, -y1))

    # Thai: raised tone marks for stacking over upper vowels / sara am.
    # U+F700..F704 = U+0E48..0E4C lifted above the tallest upper vowel; they reuse
    # the same bitmaps. Firmware (thai_shape) substitutes them where needed.
    by_cp = {g[0]: g for g in glyphs}
    if all(c in by_cp for c in (0x0E35, 0x0E48, 0x0E4C)):
        vowel_top = max(by_cp[c][6] + by_cp[c][4] for c in (0x0E31, 0x0E34, 0x0E35, 0x0E36, 0x0E37, 0x0E4D)
                        if c in by_cp)                     # ofs_y + box_h
        gap = max(1, size // 16)
        for i, tc in enumerate(range(0x0E48, 0x0E4D)):
            _, idx, adv, w, h, ox_, oy_ = by_cp[tc]
            lift = max(0, vowel_top + gap - oy_)
            glyphs.append((0xF700 + i, idx, adv, w, h, ox_, oy_ + lift))
            top_max = max(top_max, oy_ + lift + h)
        cps = cps + [0xF700 + i for i in range(5)]

    ascent, descent = font.getmetrics()
    if "--tight" in sys.argv[6:]:
        # digits-only display fonts: line box = ink extents, so the text centres optically
        base_line = bot_max
        line_height = top_max + bot_max
    else:
        base_line = max(descent, bot_max)
        line_height = max(ascent, top_max) + base_line
    cap = -font.getbbox("H", anchor="ls")[1] if 0x48 in cps else size * 7 // 10
    xh = -font.getbbox("x", anchor="ls")[1] if 0x78 in cps else size // 2

    L = []
    L.append("/* Generated by tools/ttf2lvgl.py from %s, %d px, 4 bpp */" % (ttf.split("/")[-1], size))
    L.append('#include "lvgl.h"\n')
    L.append("static LV_ATTRIBUTE_LARGE_CONST const uint8_t glyph_bitmap[] = {")
    for i in range(0, len(bitmap), 16):
        L.append("    " + ", ".join("0x%02x" % b for b in bitmap[i:i + 16]) + ",")
    if not bitmap:
        L.append("    0x00,")
    L.append("};\n")
    L.append("static const lv_font_fmt_txt_glyph_dsc_t glyph_dsc[] = {")
    L.append("    {.bitmap_index = 0, .adv_w = 0, .box_w = 0, .box_h = 0, .ofs_x = 0, .ofs_y = 0},")
    for cp, idx, adv, w, h, ox, oy in glyphs:
        L.append("    {.bitmap_index = %d, .adv_w = %d, .box_w = %d, .box_h = %d, .ofs_x = %d, .ofs_y = %d}, /* U+%04X */"
                 % (idx, adv, w, h, ox, oy, cp))
    L.append("};\n")
    L.append("static const lv_font_fmt_txt_cmap_t cmaps[] = {")
    gid = 1
    runs = contiguous_runs(cps)
    for a, b in runs:
        L.append("    {.range_start = %d, .range_length = %d, .glyph_id_start = %d, .unicode_list = NULL,"
                 " .glyph_id_ofs_list = NULL, .list_length = 0, .type = LV_FONT_FMT_TXT_CMAP_FORMAT0_TINY},"
                 % (a, b - a + 1, gid))
        gid += b - a + 1
    L.append("};\n")
    L.append("static const lv_font_fmt_txt_dsc_t font_dsc = {")
    L.append("    .glyph_bitmap = glyph_bitmap, .glyph_dsc = glyph_dsc, .cmaps = cmaps,")
    L.append("    .kern_dsc = NULL, .kern_scale = 0, .cmap_num = %d, .bpp = 4, .kern_classes = 0, .bitmap_format = 0," % len(runs))
    L.append("};\n")
    L.append("const lv_font_t %s = {" % name)
    L.append("    .get_glyph_dsc = lv_font_get_glyph_dsc_fmt_txt,")
    L.append("    .get_glyph_bitmap = lv_font_get_bitmap_fmt_txt,")
    L.append("    .line_height = %d," % line_height)
    L.append("    .base_line = %d," % base_line)
    L.append("    .cap_height = %d," % cap)
    L.append("    .x_height = %d," % xh)
    L.append("    .subpx = LV_FONT_SUBPX_NONE,")
    L.append("    .underline_position = -1,")
    L.append("    .underline_thickness = 1,")
    L.append("    .static_bitmap = 1,")
    L.append("    .dsc = &font_dsc,")
    L.append("    .fallback = NULL,")
    L.append("    .user_data = NULL,")
    L.append("};")
    open(out, "w").write("\n".join(L) + "\n")
    print("%-20s %3d px  glyphs %3d  bitmap %6d B  line_h %d" % (name, size, len(glyphs), len(bitmap), line_height))


if __name__ == "__main__":
    main()
