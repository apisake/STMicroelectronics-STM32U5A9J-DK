/* LCD interrupts: BSP_LCD_Init() enables GFXMMU, LTDC, LTDC_ER and DSI IRQs,
   so their handlers must exist (otherwise the MCU hangs in Default_Handler). */
#include "stm32u5x9j_discovery_lcd.h"

void GFXMMU_IRQHandler(void)
{
  HAL_GFXMMU_IRQHandler(&hlcd_gfxmmu);
}

void LTDC_IRQHandler(void)
{
  HAL_LTDC_IRQHandler(&hlcd_ltdc);
}

void LTDC_ER_IRQHandler(void)
{
  HAL_LTDC_IRQHandler(&hlcd_ltdc);
}

void DSI_IRQHandler(void)
{
  HAL_DSI_IRQHandler(&hlcd_dsi);
}

/* USART1 = ST-LINK VCP: interrupt-driven receive for the set-time command */
void USART1_IRQHandler(void)
{
  HAL_UART_IRQHandler(&hcom_uart[COM1]);
}

/* Touch panel INT (PE8): only enabled while sleeping, wakes the MCU from Stop */
void EXTI8_IRQHandler(void)
{
  HAL_GPIO_EXTI_IRQHandler(TS_INT_PIN);
}

/* USER button (PC13) */
void EXTI13_IRQHandler(void)
{
  BSP_PB_IRQHandler(BUTTON_USER);
}

/* RTC Alarm A (daily alarm, also a Stop-mode wake-up source) */
